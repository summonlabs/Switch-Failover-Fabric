/// One response carrying exactly the outcome the runtime decided. Refusals are Error frames, so a
/// caller can never mistake a refusal for a result.
void answer_error(Frame& response, Code code, std::string_view detail) {
  response.header.type = MessageType::Error;
  response.payload = encode_error_payload(code, detail);
}

/// The whole protocol surface of the worker. Every request except the bootstrap Hello is
/// authorised through the coordinator's session model *before* anything is executed: a frame whose
/// session identity, epoch, boot incarnation or request sequence does not match the established
/// session is answered with an Error frame and is never executed.
Status handle_request(Coordinator& coordinator, bool durability_enabled, TimestampNs now_ns,
                      const Frame& request, Frame& response) {
  if (request.header.type == MessageType::Hello) {
    Result<HelloRequest> hello = decode_hello_request(request.payload);
    if (!hello.ok()) {
      answer_error(response, hello.status().code(), hello.status().message());
      return Status::success();
    }
    if (hello.value().format_version != kFrameFormatVersion) {
      answer_error(response, Code::VersionMismatch, "frame format version is not supported");
      return Status::success();
    }
    Result<SessionRecord> opened = coordinator.open_session(hello.value().principal);
    if (!opened.ok()) {
      answer_error(response, opened.status().code(), opened.status().message());
      return Status::success();
    }
    HelloResponse ack;
    ack.session = opened.value().id;
    ack.epoch = opened.value().epoch;
    ack.boot_digest = coordinator.boot_digest();
    ack.format_version = kFrameFormatVersion;
    ack.max_payload = static_cast<std::uint32_t>(coordinator.limits().max_frame_payload);
    ack.outcome = Code::Ok;
    response.header.type = MessageType::HelloAck;
    response.payload = encode_hello_response(ack);
    return Status::success();
  }

  // Session authority is the gate: identity alone is not authority, and the epoch, boot
  // incarnation and request sequence must all still be current.
  const Status authorised = coordinator.authorise(request.header.binding());
  if (!authorised.ok()) {
    answer_error(response, authorised.code(), authorised.message());
    return Status::success();
  }

  switch (request.header.type) {
    case MessageType::QueryAuthority: {
      Result<AuthorityQueryRequest> query = decode_authority_query(request.payload);
      if (!query.ok()) {
        answer_error(response, query.status().code(), query.status().message());
        return Status::success();
      }
      Result<AuthorityQuery> authority = coordinator.query_authority(query.value().dependent);
      if (!authority.ok()) {
        answer_error(response, authority.status().code(), authority.status().message());
        return Status::success();
      }
      AuthorityQueryResponse answer;
      answer.outcome = authority.value().outcome;
      answer.reason = authority.value().reason;
      answer.has_authority = authority.value().has_authority;
      answer.active_grants = authority.value().active_grants.size();
      answer.withdrawn_grants = authority.value().withdrawn_grants.size();
      answer.fenced_generations = authority.value().fenced_generations.size();
      answer.digest = authority.value().digest();
      response.header.type = MessageType::AuthorityResult;
      response.payload = encode_authority_response(answer);
      return Status::success();
    }
    case MessageType::DeclareFailure: {
      Result<FailoverRequest> declared = decode_failover_request(request.payload);
      if (!declared.ok()) {
        answer_error(response, declared.status().code(), declared.status().message());
        return Status::success();
      }
      FailureDeclaration declaration;
      declaration.subject = declared.value().subject;
      declaration.source = declared.value().source;
      declaration.observed_at_ns =
          declared.value().observed_at_ns == 0 ? now_ns : declared.value().observed_at_ns;
      declaration.valid_for_ns =
          declared.value().valid_for_ns == 0 ? kDefaultValidityNs : declared.value().valid_for_ns;
      declaration.reason = declared.value().reason;

      Result<FailoverOutcome> outcome = coordinator.declare_failure(declaration);
      if (!outcome.ok()) {
        answer_error(response, outcome.status().code(), outcome.status().message());
        return Status::success();
      }
      FailoverResponse answer;
      answer.outcome = outcome.value().outcome;
      answer.fence_id = outcome.value().fence.raw();
      answer.fence_scope = static_cast<std::uint32_t>(outcome.value().fence_scope);
      answer.closure_complete = !outcome.value().closure.truncated() &&
                                outcome.value().closure.enumerates_every_root();
      answer.closure_members = outcome.value().closure.members.size();
      answer.grants_fenced = outcome.value().grants_fenced;
      answer.closure_digest = outcome.value().closure.digest();
      response.header.type = MessageType::FailoverResult;
      response.payload = encode_failover_response(answer);
      return Status::success();
    }
    case MessageType::QueryRestore: {
      Result<RestoreQueryRequest> query = decode_restore_query(request.payload);
      if (!query.ok()) {
        answer_error(response, query.status().code(), query.status().message());
        return Status::success();
      }
      Result<RestoreDecision> decision = coordinator.evaluate_restore(query.value().dependent);
      if (!decision.ok()) {
        answer_error(response, decision.status().code(), decision.status().message());
        return Status::success();
      }
      RestoreQueryResponse answer;
      answer.outcome = decision.value().outcome;
      answer.reason = decision.value().reason;
      answer.may_restore = decision.value().may_restore;
      answer.effect_verified = decision.value().effect_verified;
      answer.blocking_generations = decision.value().blocking_generations.size();
      response.header.type = MessageType::RestoreResult;
      response.payload = encode_restore_response(answer);
      return Status::success();
    }
    case MessageType::SnapshotRequest: {
      const TopologySnapshot* topology = coordinator.topology();
      const FailureTable* failures = coordinator.failures();
      const AuthorityRegistry* authority = coordinator.authority();
      SnapshotResponse answer;
      answer.outcome = Code::Ok;
      answer.epoch = coordinator.epoch().raw();
      answer.boot_ordinal = coordinator.boot().boot_ordinal();
      answer.switches = topology == nullptr ? 0 : topology->switches().size();
      answer.fences = authority == nullptr ? 0 : authority->fence_count();
      answer.failures = failures == nullptr ? 0 : failures->size();
      answer.active_grants = authority == nullptr ? 0 : authority->active_grant_count();
      answer.retained_events = coordinator.events(coordinator.limits().max_event_records).size();
      answer.durability_enabled = durability_enabled;
      response.header.type = MessageType::SnapshotResult;
      response.payload = encode_snapshot_response(answer);
      return Status::success();
    }
    default:
      answer_error(response, Code::Unsupported,
                   "this worker does not serve that message type");
      return Status::success();
  }
}

int run_serve(const Options& options) {
  ManualClock clock{1000};
  CoordinatorConfig config;
  config.limits = Limits::defaults();
  config.evidence_class = EvidenceClass::Synthetic;
  config.enable_durability = options.has_root;
  if (options.has_root) config.durable_root = options.root;

  Result<std::unique_ptr<Coordinator>> opened = Coordinator::open(config, &clock);
  if (!opened.ok()) {
    return fail_startup("coordinator could not be opened: " + opened.status().to_string());
  }
  std::unique_ptr<Coordinator> coordinator = std::move(opened).value();

  // SYNTHETIC two-tier fabric, generated deterministically in this process.
  Result<sfftest::Fabric> built = sfftest::build_fabric(sfftest::FabricSpec{});
  if (!built.ok()) return fail_startup("synthetic fabric could not be built: " + built.status().to_string());
  const sfftest::Fabric& fabric = built.value();

  Status installed = coordinator->install_topology(fabric.topology);
  if (!installed.ok()) return fail_startup("topology could not be installed: " + installed.to_string());
  installed = coordinator->install_candidates(fabric.candidates);
  if (!installed.ok()) return fail_startup("candidate table could not be installed: " + installed.to_string());

  // Authoritative affirmative health for every generation in the fixture, so the fabric starts
  // out usable and a later failure is a change of state rather than a pre-existing condition.
  std::vector<SwitchKey> keys = fabric.leaf_keys;
  keys.insert(keys.end(), fabric.spine_keys.begin(), fabric.spine_keys.end());
  keys.insert(keys.end(), fabric.replacement_keys.begin(), fabric.replacement_keys.end());
  std::uint64_t next_evidence = 1;
  for (const SwitchKey& key : keys) {
    EvidenceRecord record;
    record.id = EvidenceId(next_evidence++);
    record.kind = EvidenceKind::SwitchHealth;
    record.source = EvidenceSource::FabricManager;
    record.subject = key;
    record.observed_at_ns = clock.now_ns();
    record.valid_for_ns = 60ull * kNanosPerSecond;
    record.health = SwitchHealthState::Healthy;
    record.detail = "SYNTHETIC fixture observation";
    const Status admitted = coordinator->admit_evidence(record);
    if (!admitted.ok()) return fail_startup("health evidence could not be admitted: " + admitted.to_string());
  }

  ServerOptions server_options;
  server_options.bind_address = "127.0.0.1";
  server_options.port = options.has_port ? options.port : 0;
  server_options.limits = Limits::defaults();

  Coordinator* borrowed = coordinator.get();
  Result<std::unique_ptr<FrameServer>> started =
      FrameServer::start(server_options,
                         [borrowed, &clock, durable = options.has_root](const Frame& request,
                                                                        Frame& response) {
                           return handle_request(*borrowed, durable, clock.now_ns(), request,
                                                 response);
                         });
  if (!started.ok()) return fail_startup("frame server could not be started: " + started.status().to_string());
  std::unique_ptr<FrameServer> server = std::move(started).value();

  // Exactly one line on stdout, flushed: the parent reads it from a redirected handle.
  std::printf("READY port=%u epoch=%llu boot=%llu\n", static_cast<unsigned>(server->port()),
              static_cast<unsigned long long>(coordinator->epoch().raw()),
              static_cast<unsigned long long>(coordinator->boot().boot_ordinal()));
  std::fflush(stdout);

  // Serve until the parent closes our stdin. This is a real end-of-file, not a timeout: the
  // parent owns the write end of the pipe and either closes it or kills this process outright.
  while (std::fgetc(stdin) != EOF) {
  }

  const Status stopped = server->stop();
  const Status shut = coordinator->shutdown();
  if (!stopped.ok()) return fail_startup("frame server did not stop cleanly: " + stopped.to_string());
  if (!shut.ok()) return fail_startup("coordinator did not shut down cleanly: " + shut.to_string());
  return 0;
}

