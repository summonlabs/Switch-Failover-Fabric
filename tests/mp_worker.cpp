// This executable exists so that the multiprocess suite can drive the real runtime across a real
// operating-system process boundary and over really connected loopback TCP sockets. Nothing here
// is a thread, an in-process stub or a mock transport.
//
// Commands:
//   serve  --port N --root DIR   serve the framed protocol until stdin reaches EOF
//   replay --root DIR            replay a journal and report the durable lineage that survived
//   hold   --root DIR --marker F commit a failure durably, write F, then block on stdin
//
// --root DIR enables durability over that directory; without it the runtime is in memory.
//
// SYNTHETIC: the fabric is generated by sfftest::build_fabric (a synthetic two-tier topology).
// No physical switch, NIC, RDMA device or multi-node fabric is exercised by this program, and no
// result it produces may be reported as physical-hardware evidence.

