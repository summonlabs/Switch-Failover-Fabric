struct JournalScan {
  std::size_t records = 0;
  std::size_t corrupt = 0;
  std::size_t torn = 0;
  bool clean = false;
  std::uint64_t last_sequence = 0;
  std::vector<Record> decoded;
};

/// Independent read-only scan of the journal bytes. Used only when the durable store itself
/// refuses to open the journal, so that the refusal can be reported with real numbers instead of
/// a placeholder.
JournalScan scan_journal(const std::filesystem::path& path, const Limits& limits) {
  JournalScan scan;
  std::ifstream input(path, std::ios::binary);
  if (!input) return scan;
  std::vector<std::uint8_t> bytes;
  std::uint8_t chunk[64 * 1024];
  while (input) {
    input.read(reinterpret_cast<char*>(chunk), static_cast<std::streamsize>(sizeof(chunk)));
    const std::streamsize got = input.gcount();
    if (got <= 0) break;
    bytes.insert(bytes.end(), chunk, chunk + static_cast<std::size_t>(got));
  }

  std::size_t offset = 0;
  bool first = true;
  while (offset < bytes.size()) {
    const DecodeResult decoded =
        decode_record(bytes.data() + offset, bytes.size() - offset, limits);
    if (decoded.disposition == DecodeDisposition::Complete) {
      if (!first && decoded.record.header.seq <= scan.last_sequence) {
        scan.corrupt += 1;
        return scan;
      }
      first = false;
      scan.records += 1;
      scan.last_sequence = decoded.record.header.seq;
      scan.clean = decoded.record.header.kind == RecordKind::ShutdownClean;
      scan.decoded.push_back(decoded.record);
      offset += decoded.consumed;
      continue;
    }
    if (decoded.disposition == DecodeDisposition::TornTail) {
      scan.torn += 1;
      return scan;
    }
    scan.corrupt += 1;
    return scan;
  }
  return scan;
}

void print_replay_line(std::size_t records, std::size_t corrupt, std::size_t torn, bool clean,
                       std::uint64_t last_sequence) {
  std::printf("REPLAY records=%llu corrupt=%llu torn=%llu clean=%d last_seq=%llu\n",
              static_cast<unsigned long long>(records),
              static_cast<unsigned long long>(corrupt),
              static_cast<unsigned long long>(torn), clean ? 1 : 0,
              static_cast<unsigned long long>(last_sequence));
  std::fflush(stdout);
}

void print_lineage(const std::vector<Record>& records) {
  for (const Record& record : records) {
    if (record.header.kind == RecordKind::FailureCommitted) {
      const Result<FailureRecord> decoded = decode_failure_record(record.payload);
      if (!decoded.ok()) continue;
      std::printf("LINEAGE failure %llu@%llu\n",
                  static_cast<unsigned long long>(decoded.value().subject.id().raw()),
                  static_cast<unsigned long long>(decoded.value().subject.generation().raw()));
    } else if (record.header.kind == RecordKind::FenceCommitted) {
      const Result<FenceRecord> decoded = decode_fence_record(record.payload);
      if (!decoded.ok()) continue;
      std::printf("LINEAGE fence %llu@%llu\n",
                  static_cast<unsigned long long>(decoded.value().subject.id().raw()),
                  static_cast<unsigned long long>(decoded.value().subject.generation().raw()));
    }
  }
  std::fflush(stdout);
}

int run_replay(const Options& options) {
  StoreOptions store_options;
  store_options.root = options.root;
  store_options.limits = Limits::defaults();
  store_options.mode = OpenMode::OpenOrCreate;
  store_options.durable_writes = true;

  Result<std::unique_ptr<DurableStore>> opened = DurableStore::open(store_options);
  if (!opened.ok()) {
    // A complete record that fails its integrity check is never repaired or skipped, so the store
    // refuses to open the journal at all. Report what an independent scan of the same bytes found
    // and exit non-zero: corruption is an explicit outcome, never an ordinary absence.
    const JournalScan scan =
        scan_journal(store_options.root / "sff.journal", store_options.limits);
    print_replay_line(scan.records, scan.corrupt, scan.torn, false, scan.last_sequence);
    print_lineage(scan.decoded);
    std::fprintf(stderr, "mp_worker replay: journal refused: %s\n",
                 opened.status().to_string().c_str());
    std::fflush(stderr);
    return 1;
  }

  std::unique_ptr<DurableStore> store = std::move(opened).value();
  const ReplayReport& report = store->open_report();
  print_replay_line(report.records.size(), report.corrupt_records, report.torn_records,
                    report.clean_shutdown, report.last_sequence);
  print_lineage(report.records);
  const Status closed = store->close();
  if (!closed.ok()) return fail_startup("durable store did not close cleanly: " + closed.to_string());
  return 0;
}

