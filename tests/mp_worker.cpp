constexpr int kUsageError = 2;
constexpr int kStartupError = 3;

/// Seconds of validity stamped on a declaration whose request carries no window.
constexpr std::uint64_t kDefaultValidityNs = 3600ull * kNanosPerSecond;

struct Options {
  std::string command;
  std::uint16_t port = 0;
  bool has_port = false;
  std::filesystem::path root;
  bool has_root = false;
  std::filesystem::path marker;
  bool has_marker = false;
};

int fail_startup(const std::string& message) {
  std::fprintf(stderr, "mp_worker: %s\n", message.c_str());
  std::fflush(stderr);
  return kStartupError;
}

void usage() {
  std::fprintf(stderr,
               "usage:\n"
               "  mp_worker serve  --port N --root DIR\n"
               "  mp_worker replay --root DIR\n"
               "  mp_worker hold   --root DIR --marker FILE\n");
  std::fflush(stderr);
}

bool parse_options(int argc, char** argv, Options& out) {
  if (argc < 2) return false;
  out.command = argv[1];
  for (int index = 2; index < argc; ++index) {
    const std::string flag = argv[index];
    const bool has_value = index + 1 < argc;
    if (flag == "--port" && has_value) {
      const char* text = argv[++index];
      char* end = nullptr;
      const long value = std::strtol(text, &end, 10);
      if (end == text || *end != '\0' || value < 0 || value > 65535) return false;
      out.port = static_cast<std::uint16_t>(value);
      out.has_port = true;
    } else if (flag == "--root" && has_value) {
      out.root = std::filesystem::path(argv[++index]);
      out.has_root = true;
    } else if (flag == "--marker" && has_value) {
      out.marker = std::filesystem::path(argv[++index]);
      out.has_marker = true;
    } else {
      return false;
    }
  }
  return true;
}

